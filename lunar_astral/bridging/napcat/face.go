// faceDisplayText 解析 QQ 表情的文本含义：
// 优先 NapCat 原始 faceText（形如 "/呲牙"），其次 raw.faceIndex，最后按 id 查官方对照表；无法识别返回空
func faceDisplayText(data json.RawMessage) string {
	var face FaceData
	if json.Unmarshal(data, &face) != nil {
		return ""
	}
	if face.Raw != nil {
		if text := normalizeFaceText(face.Raw.FaceText); text != "" {
			return text
		}
		if face.Raw.FaceIndex != nil {
			if text, ok := qqFaceTextMap[*face.Raw.FaceIndex]; ok {
				return text
			}
		}
	}
	if id, err := strconv.Atoi(strings.TrimSpace(rawIDString(face.ID))); err == nil {
		if text, ok := qqFaceTextMap[id]; ok {
			return text
		}
	}
	return ""
}

// normalizeFaceText 规整 NTQQ 表情文本：剥掉前缀 "/" 并去除首尾空白
func normalizeFaceText(text string) string {
	return strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(text), "/"))
}
